-- Pokreni u Supabase → SQL Editor.

ALTER TABLE public.product
  ADD COLUMN IF NOT EXISTS order_no integer NOT NULL DEFAULT 1000;

ALTER TABLE public.product_category
  ADD COLUMN IF NOT EXISTS order_no integer;

UPDATE public.product_category
SET order_no = id
WHERE order_no IS NULL;

ALTER TABLE public.product_category
  ALTER COLUMN order_no SET DEFAULT 1000;

ALTER TABLE public.product_category
  ALTER COLUMN order_no SET NOT NULL;

CREATE TABLE IF NOT EXISTS public.home_slide (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  is_active boolean NOT NULL DEFAULT true,
  order_no integer NOT NULL DEFAULT 1000,
  starts_at timestamptz NULL,
  ends_at timestamptz NULL,
  badge text NULL,
  title text NOT NULL DEFAULT '',
  subtitle text NULL,
  description text NULL,
  image_url text NULL,
  price_label text NULL,
  product_id bigint NULL REFERENCES public.product (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS home_slide_order_idx
  ON public.home_slide (is_active, order_no);

CREATE TABLE IF NOT EXISTS public.featured_product (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.product (id) ON DELETE CASCADE,
  is_active boolean NOT NULL DEFAULT true,
  order_no integer NOT NULL DEFAULT 1000,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (product_id)
);

CREATE INDEX IF NOT EXISTS featured_product_order_idx
  ON public.featured_product (is_active, order_no);

CREATE TABLE IF NOT EXISTS public.category_highlight (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.product (id) ON DELETE CASCADE,
  is_active boolean NOT NULL DEFAULT true,
  order_no integer NOT NULL DEFAULT 1000,
  badge text NULL,
  promo_title text NULL,
  promo_description text NULL,
  image_url text NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS category_highlight_order_idx
  ON public.category_highlight (is_active, order_no);

ALTER TABLE public.home_slide ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.featured_product ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.category_highlight ENABLE ROW LEVEL SECURITY;

